const getNestedValue = (source, path) => String(path || '')
  .split('.')
  .filter(Boolean)
  .reduce((current, key) => (
    current && Object.prototype.hasOwnProperty.call(current, key) ? current[key] : undefined
  ), source);

const interpolate = (value, params = {}) => {
  if (typeof value !== 'string') return value;
  return value.replace(/\{\{\s*([\w.-]+)\s*\}\}/g, (_, key) => (
    Object.prototype.hasOwnProperty.call(params || {}, key) ? String(params[key]) : ''
  ));
};

export function useEditorPanelText(namespace) {
  const { language } = useI18n();

  const readSource = useCallback((sourceLanguage, key) => (
    getNestedValue(EDITOR_PANEL_TRANSLATIONS[sourceLanguage]?.[namespace], key)
  ), [namespace]);

  const tx = useCallback((key, params = {}, fallback = '') => {
    const translatedValue = readSource(language, key);
    const defaultValue = readSource(DEFAULT_LANGUAGE, key);
    const value = translatedValue ?? defaultValue ?? fallback;
    if (typeof value === 'string') return interpolate(value, params);
    return typeof fallback === 'string' && fallback ? interpolate(fallback, params) : key;
  }, [language, readSource]);

  const txObject = useCallback((key, fallback = {}) => {
    const translatedValue = readSource(language, key);
    const defaultValue = readSource(DEFAULT_LANGUAGE, key);
    return translatedValue ?? defaultValue ?? fallback;
  }, [language, readSource]);

  return { tx, txObject, language };
}
