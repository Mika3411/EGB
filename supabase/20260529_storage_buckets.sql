create policy "Escape game public assets are readable"
on storage.objects
for select
to anon, authenticated
using (
  bucket_id = public.escape_game_public_assets_bucket_id()
);

comment on policy "Escape game public assets are readable" on storage.objects
is 'Allows anonymous and authenticated reads only from the public assets bucket.';

create policy "Escape game users can upload own public assets"
on storage.objects
for insert
to authenticated
with check (
  bucket_id = public.escape_game_public_assets_bucket_id()
  and public.escape_game_storage_is_safe_user_path(name, auth.uid())
);

comment on policy "Escape game users can upload own public assets" on storage.objects
is 'Allows browser uploads to the public bucket only under users/{auth.uid()}/... paths.';

create policy "Escape game users can update own public assets"
on storage.objects
for update
to authenticated
using (
  bucket_id = public.escape_game_public_assets_bucket_id()
  and public.escape_game_storage_is_safe_user_path(name, auth.uid())
)
with check (
  bucket_id = public.escape_game_public_assets_bucket_id()
  and public.escape_game_storage_is_safe_user_path(name, auth.uid())
);

create policy "Escape game users can delete own public assets"
